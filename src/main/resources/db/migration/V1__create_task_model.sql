-- Task model (story 008): see docs/architecture/data-model.md
CREATE TABLE task (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title             VARCHAR(120) NOT NULL CHECK (char_length(title) >= 1),
    description       TEXT,
    estimated_minutes INTEGER      NOT NULL CHECK (estimated_minutes >= 1),
    planned_for       DATE,
    reminder_at       TIMESTAMP(6),
    status            VARCHAR(20)  NOT NULL CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE')),
    created_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

-- At most one unfinished task per planned day (REG-02)
CREATE UNIQUE INDEX uk_task_planned_for_unfinished ON task (planned_for) WHERE status <> 'DONE';

CREATE TABLE task_step (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id           BIGINT      NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    label             VARCHAR(80) NOT NULL CHECK (char_length(label) >= 1),
    estimated_minutes INTEGER     NOT NULL CHECK (estimated_minutes BETWEEN 1 AND 30),
    position          INTEGER     NOT NULL,
    done              BOOLEAN     NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_task_step_position UNIQUE (task_id, position)
);

CREATE TABLE notification_log (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_id BIGINT      NOT NULL REFERENCES task (id) ON DELETE CASCADE,
    channel VARCHAR(20) NOT NULL CHECK (channel IN ('DISCORD', 'IN_APP')),
    sent_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    success BOOLEAN     NOT NULL
);

CREATE INDEX ix_notification_log_task ON notification_log (task_id);
